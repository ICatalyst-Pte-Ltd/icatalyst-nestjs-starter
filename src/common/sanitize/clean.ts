export function clean<T>(value: T): T {
  return typeof value === 'string'
    ? (cleanString(value) as T)
    : value != null && typeof value === 'object'
      ? (cleanObject(value) as T)
      : value;
}

function cleanString(text: string): string {
  const clean = sanitizeHtml(text, {
    allowedAttributes: DEFAULT_ALLOWED_ATTRIBUTES,
    allowedTags: DEFAULT_ALLOWED_TAGS,
  });
  return clean;
}

function cleanObject(object: object): object {
  return Array.isArray(object)
    ? cleanArray(object)
    : Object.fromEntries(Object.entries(object).map(cleanEntry));
}

function cleanArray<T>(array: ReadonlyArray<T>): ReadonlyArray<T> {
  return array.map(clean);
}

function cleanEntry<K, V>([key, value]: [K, V]): [K, V] {
  return [clean(key), clean(value)];
}
